# ---------------------------------------------------------------------------
# init-prod.ps1 — create the production-profile stack from scratch.
#
#   pwsh -File deploy/migrate/init-prod.ps1
#
# What it does:
#   1. generates deploy/config/prod.env with strong random credentials (never
#      touches an existing file, so re-running is safe);
#   2. restricts the ACL of that secret file to the current user;
#   3. pins the verified node/web images as lattice-node:prod / lattice-web:prod
#      (they are tagged from the existing :dev images built from this same tree);
#   4. validates and starts deploy/compose/prod.yaml;
#   5. waits until the node and the console answer.
#
# The stack is isolated from the development stack: its own Compose project
# (lattice-prod), volumes, network and host ports (console 8089).
#
# After this script finishes, run:  node deploy/migrate/seed.mjs
# ---------------------------------------------------------------------------
$ErrorActionPreference = 'Stop'
$ProgressPreference = 'SilentlyContinue'

$RepoRoot = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
Set-Location $RepoRoot

$EnvFile = Join-Path $RepoRoot 'deploy/config/prod.env'
$ComposeFile = 'deploy/compose/prod.yaml'

# Windows PowerShell 5.1 (.NET Framework) compatible: RandomNumberGenerator.Fill
# and Convert.ToHexString do not exist there, so use GetBytes + x2 formatting.
function New-AlphaSecret([int]$Length) {
  $chars = 'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'
  $bytes = New-Object byte[] $Length
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  try { $rng.GetBytes($bytes) } finally { $rng.Dispose() }
  return -join ($bytes | ForEach-Object { $chars[$_ % $chars.Length] })
}

function New-HexSecret([int]$Bytes) {
  $buf = New-Object byte[] $Bytes
  $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
  try { $rng.GetBytes($buf) } finally { $rng.Dispose() }
  return -join ($buf | ForEach-Object { $_.ToString('x2') })
}

function Wait-Http([string]$Url, [int]$TimeoutSeconds) {
  $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
  $last = ''
  while ((Get-Date) -lt $deadline) {
    try {
      $res = Invoke-WebRequest -Uri $Url -TimeoutSec 3 -UseBasicParsing
      if ($res.StatusCode -eq 200) { return $true }
      $last = "HTTP $($res.StatusCode)"
    } catch {
      $last = $_.Exception.Message
    }
    Start-Sleep -Seconds 1
  }
  throw "timed out waiting for $Url ($last)"
}

# ---- 1) credentials ---------------------------------------------------------
if (Test-Path $EnvFile) {
  Write-Host "[1/5] keeping existing secrets: $EnvFile"
} else {
  Write-Host "[1/5] generating production secrets: $EnvFile"

  $PgPassword = New-AlphaSecret 32
  $RedisPassword = New-AlphaSecret 32
  $MinioUser = 'lattice_prod'
  $MinioPassword = New-AlphaSecret 40
  $TransferSecret = New-HexSecret 32   # 64 hex chars = 32 bytes (minimum accepted by [transfer])
  $BootstrapPassword = New-AlphaSecret 28

  $content = @"
# Lattice production-profile secrets. Generated by deploy/migrate/init-prod.ps1.
# Never commit this file (it is git-ignored). Values are consumed by Docker Compose
# through env_file:, not through Compose interpolation.

# PostgreSQL
POSTGRES_PASSWORD=$PgPassword
LATTICE__PG__URL=postgres://lattice_app:$PgPassword@pg:5432/lattice?sslmode=disable

# Redis (password protected)
REDIS_PASSWORD=$RedisPassword
LATTICE__REDIS__URL=redis://:$RedisPassword@redis:6379/0

# MinIO / S3
MINIO_ROOT_USER=$MinioUser
MINIO_ROOT_PASSWORD=$MinioPassword
LATTICE__S3__ACCESS_KEY=$MinioUser
LATTICE__S3__SECRET_KEY=$MinioPassword

# NATS JetStream (no app-level auth: async-nats 0.53 ignores URL userinfo; the
# client port is loopback-only and private to the Compose network)
LATTICE__BUS__NATS_URL=nats://nats:4222

# Download transfer plane (shared HMAC secret, node + transfer)
LATTICE__TRANSFER__SECRET=$TransferSecret

# First-boot administrator only; seed.mjs blanks this after the real admin account
# has been migrated and verified.
LATTICE__ADMIN__BOOTSTRAP_PASSWORD=$BootstrapPassword

# Runtime
LATTICE__NODE__METRICS=0.0.0.0:9100
RUST_LOG=info,lattice_node=info
"@

  [System.IO.File]::WriteAllText($EnvFile, $content, [System.Text.UTF8Encoding]::new($false))
}

# ---- 2) ACL ----------------------------------------------------------------
Write-Host "[2/5] restricting secret file ACL to $env:USERNAME"
try {
  $null = icacls $EnvFile /inheritance:r /grant:r "$($env:USERNAME):(R,W)" 2>&1
} catch {
  Write-Warning "could not tighten the ACL of $EnvFile : $($_.Exception.Message)"
}

# ---- 3) images -------------------------------------------------------------
function Test-Image([string]$Tag) {
  $previous = $ErrorActionPreference
  $ErrorActionPreference = 'SilentlyContinue'
  try {
    docker image inspect $Tag 2>$null | Out-Null
    return ($LASTEXITCODE -eq 0)
  } finally {
    $ErrorActionPreference = $previous
  }
}

Write-Host "[3/5] pinning production images"
foreach ($name in @('lattice-node', 'lattice-web')) {
  $prodTag = "${name}:prod"
  if (-not (Test-Image $prodTag)) {
    if (-not (Test-Image "${name}:dev")) {
      throw "image ${name}:dev is missing; build the stack with 'docker compose -f deploy/compose/dev.yaml build' first"
    }
    docker tag "${name}:dev" $prodTag
    Write-Host "  tagged ${name}:dev -> $prodTag"
  } else {
    Write-Host "  $prodTag already present"
  }
}

# ---- 4) start --------------------------------------------------------------
Write-Host "[4/5] validating and starting $ComposeFile"
docker compose -f $ComposeFile config --quiet
if ($LASTEXITCODE -ne 0) { throw 'compose configuration is invalid' }

docker compose -f $ComposeFile up -d
if ($LASTEXITCODE -ne 0) { throw 'docker compose up failed' }

# ---- 5) readiness ---------------------------------------------------------
Write-Host "[5/5] waiting for readiness"
Wait-Http 'http://127.0.0.1:8180/v1/ready' 240 | Out-Null
Wait-Http 'http://127.0.0.1:8089/v1/health' 120 | Out-Null

Write-Host ''
Write-Host 'Production stack is up.'
Write-Host '  console : http://127.0.0.1:8089'
Write-Host '  node    : http://127.0.0.1:8180/v1/health'
Write-Host '  secrets : deploy/config/prod.env'
Write-Host ''
Write-Host 'Next: node deploy/migrate/seed.mjs'

//! QUIC / WebTransport media plane (P4, ② §3.5; the default path order is authoritative in §17.9).
//!
//! Order: ① WebRTC direct (default) → ② QUIC server proxy (switch on demand) → ③ WS `stream-data` tunnel (fallback).
//!
//! # Implementation status (PL-13 13.3: minimal skeleton + JWT/device binding + SIGTERM drain; still not the final form of §17.9)
//!
//! - Dual switches: compile-time feature `quic` (**off** by default) + runtime `[quic] enabled` (default `false`);
//!   when not enabled, this file only has the constants/path selection below, with zero dependencies (quinn/rustls are not compiled) and zero tasks.
//! - When enabled: UDP listener (TLS 1.3, ALPN `lattice-quic-media/1`, certificate configurable as PEM, dev self-signed temporary certificate by default)
//!   + `stream_id` registry (connection pool) + bidirectional verbatim relay + bye/disconnect cleanup + Prometheus metrics;
//!   registration auth = access JWT (signature/expiry/issuer) + devices-table binding (user/fingerprint/revocation) +
//!   stream-sig session participant (a/b role) validation; the join token is a short-lived single-use HMAC ticket.
//! - Rate limits/caps **reuse `[media]`**: the 8Mbps per-stream token bucket reuses `routing::media::allow_stream_bytes`
//!   (the same bucket implementation as the WS tunnel, bucketed only by `stream_id`), and the per-node stream cap reuses `[media] max_streams`.
//!
//! ## Gaps versus the design's final form (stated truthfully, no false claims)
//!
//! 1. **Not WebTransport**: only private TLV frames run over QUIC (`[1B type][4B len BE][payload]`),
//!    with no HTTP/3, no WebTransport CONNECT streams, and no datagram/`stream-data` conversion;
//! 2. **Auth is bound to JWT/device (completed in PL-13 13.3)**: the register frame must carry `access_jwt` + `device_fp`,
//!    the server takes identity from JWT claims (never trusting a client-reported user), verifies `devices` table ownership/fingerprint/revocation,
//!    and requires that `(user, device)` to be a participant of the `stream-sig` session (`lattice:stream:{id}`) for the
//!    corresponding role (a/b); the join token is a short-lived ticket issued with a server-side HMAC (bound to stream_id + purpose + expiry,
//!    single-use). What is still missing is "issuing tokens for both ends at the signaling layer", which itself requires changing `routing/media.rs`
//!    (explicitly out of scope for this task), so **issuance** of the token still happens in the QUIC register response;
//! 3. **No cross-node support**: the registry is in process memory, so A/B must land on the same node (the cross-node proxy/recording
//!    bypasses of design §17.9 are not wired up); there is no WebRTC↔QUIC interop, no SFU/transcoding/adaptive bitrate;
//! 4. **Graceful shutdown**: once `AppState.draining` (shared by SIGTERM/ctrl-c/admin drain) is set, stop accepting new
//!    QUIC connections, send `bye{reason:"shutdown"}` to registered streams, and close the endpoint after a bounded wait; the SIGTERM hook in `main.rs`
//!    calls [`drain`] directly so this always runs before the process exits (see "Lifecycle" below);
//! 5. **E2E uses temporary certificates** (dev CA/server generated by `scripts/gen-grpc-certs.py`); the dev self-signed cert is only for
//!    manual local testing, and the sample client **skips certificate verification** when `--ca` is absent (dev only, explicitly marked in the code).
//!
//! ## QUIC proxy protocol v1 (private TLS-ALPN, not h3)
//!
//! One QUIC connection carries **one** relay stream (`stream_id`); after `connect` the client immediately calls `open_bi` and
//! exchanges frames on that bidirectional stream (`[1B type][4B payload_len BE][payload]`):
//!
//! ```text
//! type 1 = CONTROL: UTF-8 JSON; type 2 = DATA: opaque media bytes (single frame ≤ 64KiB, §17.10)
//! ```
//!
//! 1. The initiator `a` sends `{"t":"register","v":1,"stream_id":"...","role":"a",
//!    "access_jwt":"...","device_fp":"..."}` (precondition: A has already established the session via a WS `stream-sig` offer);
//!    the server replies `{"t":"registered",...,"join_token":"..","session_token":".."}` (`join_token` is passed to B via signaling);
//! 2. The joiner `b` sends `{"t":"register","v":1,"stream_id":"...","role":"b","token":"<join_token>",
//!    "access_jwt":"...","device_fp":"..."}`; once the JWT identity matches the session's b side and the token matches, is unexpired and unused,
//!    the server sends `{"t":"peer_ready"}` to both ends, after which DATA is relayed verbatim in both directions;
//! 3. On auth failure the server replies `{"t":"error","code":"AUTH_FAIL"|"FORBIDDEN","reason":"expired|bad_jwt|
//!    device_mismatch|not_participant","message":"..."}` and then closes the connection;
//! 4. `{"t":"bye"}` = half-close: the server forwards it to the peer and FINs the peer's send stream; once both connections close, the registry/metrics are cleaned up;
//!    a QUIC disconnect on either end triggers the same cleanup (`lattice_quic_dropped_total{reason="closed"}`).
//!
//! The server does not interpret DATA payloads (same as the WS tunnel: media codecs live in the client).
//!
//! # Lifecycle (SIGTERM / drain)
//!
//! `AppState.draining` is the drain flag shared by WS and the admin plane (set by `ws::drain_all`). On the QUIC side:
//! 1. as soon as the accept loop observes draining it stops accepting new connections (in-flight `Incoming` are refused outright);
//! 2. for each stream in the registry, `notify` the relay write side/wait side: the write side sends `bye{reason:"shutdown"}` and FINs;
//!    an A side not yet paired writes bye directly and cleans up;
//! 3. after a bounded wait (`handshake_timeout` clamped to [2s,5s]) for the registry to empty, `endpoint.close(0,"shutdown")`
//!    closes leftover connections/rejects new handshakes, and finally the registry is cleaned up as a fallback and a log is written.
//!
//! Idempotent: the SIGTERM hook in `main.rs` and the draining watcher task may fire simultaneously; only the first one takes effect.



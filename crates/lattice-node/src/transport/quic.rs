    struct TlsMaterial {
        certs: Vec<CertificateDer<'static>>,
        key: PrivateKeyDer<'static>,
        /// true = this startup generated a dev self-signed temporary certificate (in memory only).
        self_signed: bool,
    }

    fn load_tls_material(cfg: &QuicCfg) -> crate::Result<TlsMaterial> {
        let cert_path = cfg.cert.trim();
        let key_path = cfg.key.trim();
        match (cert_path.is_empty(), key_path.is_empty()) {
            (true, true) => {
                // dev self-signed: only generated when [quic] is explicitly enabled and both paths are empty; never persisted, replaced on restart.
                let ck = rcgen::generate_simple_self_signed(vec![
                    "localhost".to_string(),
                    "127.0.0.1".to_string(),
                ])
                .map_err(|e| LatticeError::internal(format!("quic dev self-signed cert: {e}")))?;
                let cert = CertificateDer::from(ck.cert.der().to_vec());
                let key = PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(ck.key_pair.serialize_der()));
                Ok(TlsMaterial { certs: vec![cert], key, self_signed: true })
            }
            (false, false) => {
                let cert_bytes = std::fs::read(cert_path).map_err(|e| {
                    LatticeError::internal(format!("quic: read cert {cert_path} failed: {e}"))
                })?;
                let certs: Vec<CertificateDer<'static>> =
                    rustls_pemfile::certs(&mut BufReader::new(cert_bytes.as_slice()))
                        .collect::<std::result::Result<Vec<_>, _>>()
                        .map_err(|e| {
                            LatticeError::internal(format!("quic: parse cert {cert_path} failed: {e}"))
                        })?;
                if certs.is_empty() {
                    return Err(LatticeError::internal(format!(
                        "quic: cert {cert_path} contains no PEM certificate"
                    )));
                }
                let key_bytes = std::fs::read(key_path).map_err(|e| {
                    LatticeError::internal(format!("quic: read key {key_path} failed: {e}"))
                })?;
                let key = rustls_pemfile::private_key(&mut BufReader::new(key_bytes.as_slice()))
                    .map_err(|e| {
                        LatticeError::internal(format!("quic: parse key {key_path} failed: {e}"))
                    })?
                    .ok_or_else(|| {
                        LatticeError::internal(format!(
                            "quic: key {key_path} contains no PEM private key"
                        ))
                    })?;
                Ok(TlsMaterial { certs, key, self_signed: false })
            }
            _ => Err(LatticeError::internal(
                "quic: [quic] cert/key must be configured together or both left empty (empty = dev self-signed temporary certificate)",
            )),
        }
    }

    /// Build the quinn server configuration (TLS 1.3 + ALPN + stream/idle parameters).
    pub(crate) fn build_server_config(cfg: &QuicCfg) -> crate::Result<(ServerConfig, bool)> {
        let material = load_tls_material(cfg)?;
        let mut tls = rustls::ServerConfig::builder()
            .with_no_client_auth()
            .with_single_cert(material.certs, material.key)
            .map_err(|e| LatticeError::internal(format!("quic: tls server config failed: {e}")))?;
        tls.alpn_protocols = vec![ALPN.to_vec()];
        // The proxy skeleton has no 0-RTT (rustls defaults max_early_data_size=0; media frames must not allow replay guessing)

        let quic_crypto = quinn::crypto::rustls::QuicServerConfig::try_from(tls)
            .map_err(|e| LatticeError::internal(format!("quic: crypto config failed: {e}")))?;
        let mut server = ServerConfig::with_crypto(Arc::new(quic_crypto));

        let mut transport = TransportConfig::default();
        // One connection carries only one relay stream (protocol v1 simplification; concurrent multi-stream is left to a later version)
        transport.max_concurrent_bidi_streams(1u32.into());
        transport.max_concurrent_uni_streams(0u32.into());
        let idle = IdleTimeout::try_from(Duration::from_secs(cfg.effective_idle_timeout_secs()))
            .map_err(|e| LatticeError::internal(format!("quic: invalid idle timeout: {e}")))?;
        transport.max_idle_timeout(Some(idle));
        // keep-alive must be clearly shorter than the idle timeout (otherwise idle connections are mistakenly considered disconnected);
        // cap 5s, floor 500ms, taking the middle of idle/3.
        let idle_secs = cfg.effective_idle_timeout_secs();
        let keep_alive_ms = (idle_secs * 1000 / 3).clamp(500, KEEP_ALIVE.as_millis() as u64);
        transport.keep_alive_interval(Some(Duration::from_millis(keep_alive_ms)));
        server.transport_config(Arc::new(transport));
        Ok((server, material.self_signed))
    }


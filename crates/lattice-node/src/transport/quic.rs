    /// Frame header encoding (shared by tests and read/write, avoiding drift in length/byte order in two places).
    ///
    /// `pub` only so the WebTransport bridge layer in the same crate (feature `webtransport`) can reuse **the same**
    /// TLV frame definitions (control/data types and length caps) without changing any existing behavior.
    pub fn encode_header(ty: u8, len: usize) -> [u8; FRAME_HEADER] {
        let l = len as u32;
        [ty, (l >> 24) as u8, (l >> 16) as u8, (l >> 8) as u8, l as u8]
    }

    /// Frame header decoding: returns `(type, payload_len)`; an unknown type or over-limit length returns `Err(reason)`.
    pub fn decode_header(header: &[u8; FRAME_HEADER]) -> Result<(u8, usize), &'static str> {
        let ty = header[0];
        let len = u32::from_be_bytes([header[1], header[2], header[3], header[4]]) as usize;
        let max = match ty {
            FRAME_CONTROL => CONTROL_MAX,
            FRAME_DATA => DATA_MAX,
            _ => return Err("unknown frame type"),
        };
        if len > max {
            return Err("frame too large");
        }
        Ok((ty, len))
    }

    /// Read one frame; `Ok(None)` = the peer half-closed normally (FIN).
    pub async fn read_frame(
        recv: &mut RecvStream,
    ) -> Result<Option<(u8, bytes::Bytes)>, &'static str> {
        let mut header = [0u8; FRAME_HEADER];
        match recv.read_exact(&mut header).await {
            Ok(()) => {}
            // FIN falls exactly on a frame boundary = normal half-close
            Err(quinn::ReadExactError::FinishedEarly(0)) => return Ok(None),
            Err(_) => return Err("read frame header failed"),
        }
        let (ty, len) = decode_header(&header)?;
        let mut buf = vec![0u8; len];
        if !buf.is_empty() {
            recv.read_exact(&mut buf)
                .await
                .map_err(|_| "read frame payload failed")?;
        }
        Ok(Some((ty, bytes::Bytes::from(buf))))
    }

    /// Write one frame (CONTROL/DATA both go through here, keeping a single writer sequence toward the peer).
    pub async fn write_frame(
        send: &mut SendStream,
        ty: u8,
        payload: &[u8],
    ) -> Result<(), &'static str> {
        let header = encode_header(ty, payload.len());
        decode_header(&header)?; // reuse the same cap validation
        send.write_all(&header)
            .await
            .map_err(|_| "write frame header failed")?;
        if !payload.is_empty() {
            send.write_all(payload)
                .await
                .map_err(|_| "write frame payload failed")?;
        }
        Ok(())
    }


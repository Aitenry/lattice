    /// `stream_id` rules match the §17.9 signaling field (1..=64, `[A-Za-z0-9._:-]`).
    pub(crate) fn valid_stream_id(s: &str) -> bool {
        !s.is_empty()
            && s.len() <= STREAM_ID_MAX
            && s.bytes()
                .all(|b| b.is_ascii_alphanumeric() || matches!(b, b'-' | b'_' | b'.' | b':'))
    }

    fn random_token() -> String {
        let mut buf = [0u8; TOKEN_BYTES];
        rand::thread_rng().fill_bytes(&mut buf);
        hex::encode(buf)
    }

    /// Randomly generate the HMAC key for join tokens (in-process, never persisted; replaced on restart = all old tokens invalid).
    pub(crate) fn new_join_token_key() -> [u8; JOIN_TOKEN_KEY_BYTES] {
        let mut key = [0u8; JOIN_TOKEN_KEY_BYTES];
        rand::thread_rng().fill_bytes(&mut key);
        key
    }

    /// `HMAC-SHA256(key, payload)` → lowercase hex.
    fn join_token_mac(key: &[u8; JOIN_TOKEN_KEY_BYTES], payload: &str) -> String {
        let mut mac = HmacSha256::new_from_slice(key).expect("hmac accepts any key length");
        mac.update(payload.as_bytes());
        hex::encode(mac.finalize().into_bytes())
    }

    /// Issue a join token: `qj1|<stream_id>|join|<exp_unix>|<nonce_hex>|<mac_hex>`.
    ///
    /// Short-lived (`[quic] token_ttl_secs`), bound to stream_id and purpose (join), HMAC-tamper-proof;
    /// single-use (registry `join_used`) and consumable only by the session's b-side identity (participant check happens after the JWT).
    pub(crate) fn issue_join_token(
        key: &[u8; JOIN_TOKEN_KEY_BYTES],
        stream_id: &str,
        ttl: Duration,
    ) -> (String, Instant) {
        let now = chrono::Utc::now().timestamp();
        let exp = now.saturating_add(ttl.as_secs() as i64);
        let mut nonce = [0u8; 16];
        rand::thread_rng().fill_bytes(&mut nonce);
        let payload = format!(
            "{JOIN_TOKEN_PREFIX}|{stream_id}|{JOIN_TOKEN_PURPOSE}|{exp}|{}",
            hex::encode(nonce)
        );
        let mac = join_token_mac(key, &payload);
        (
            format!("{payload}|{mac}"),
            Instant::now() + ttl,
        )
    }

    /// join token verification failure classes (all rejected as `BAD_TOKEN` and counted as `token`, leaking no internal details).
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub(crate) enum JoinTokenError {
        Malformed,
        BadMac,
        WrongStream,
        WrongPurpose,
        Expired,
    }

    impl JoinTokenError {
        pub(crate) fn message(self) -> &'static str {
            match self {
                JoinTokenError::Malformed => "join token malformed",
                JoinTokenError::BadMac => "join token signature mismatch",
                JoinTokenError::WrongStream => "join token was issued for another stream_id",
                JoinTokenError::WrongPurpose => "join token purpose mismatch",
                JoinTokenError::Expired => "join token expired",
            }
        }
    }

    /// Verify a join token (HMAC + stream_id binding + purpose + expiry); single use is decided by the registry.
    pub(crate) fn verify_join_token(
        key: &[u8; JOIN_TOKEN_KEY_BYTES],
        token: &str,
        expected_stream_id: &str,
    ) -> Result<(), JoinTokenError> {
        if token.is_empty() || token.len() > JOIN_TOKEN_MAX {
            return Err(JoinTokenError::Malformed);
        }
        let parts: Vec<&str> = token.split('|').collect();
        if parts.len() != 6 || !parts[4].bytes().all(|b| b.is_ascii_hexdigit()) {
            return Err(JoinTokenError::Malformed);
        }
        if parts[0] != JOIN_TOKEN_PREFIX {
            return Err(JoinTokenError::Malformed);
        }
        if parts[2] != JOIN_TOKEN_PURPOSE {
            return Err(JoinTokenError::WrongPurpose);
        }
        let payload = &token[..token.len() - parts[5].len() - 1];
        let actual = match hex::decode(parts[5]) {
            Ok(v) => v,
            Err(_) => return Err(JoinTokenError::Malformed),
        };
        let mut mac = HmacSha256::new_from_slice(key).expect("hmac accepts any key length");
        mac.update(payload.as_bytes());
        if mac.verify_slice(&actual).is_err() {
            return Err(JoinTokenError::BadMac);
        }
        if parts[1] != expected_stream_id {
            return Err(JoinTokenError::WrongStream);
        }
        let exp: i64 = parts[3]
            .parse()
            .map_err(|_| JoinTokenError::Malformed)?;
        if chrono::Utc::now().timestamp() >= exp {
            return Err(JoinTokenError::Expired);
        }
        Ok(())
    }

    /// Register frame structure validation: returns `Err((metric_result, error_code, message))`.
    ///
    /// Only "frame shape/fields" are checked; JWT/device/participant auth happens asynchronously in [`authenticate_register`]
    /// (which needs PG/Redis); failure classes are in [`AuthFailure`].
    pub(crate) fn validate_register(
        msg: &RegisterMsg,
    ) -> Result<(), (&'static str, &'static str, &'static str)> {
        if msg.t != "register" {
            return Err(("bad_request", "BAD_REQUEST", "first control frame must be register"));
        }
        if msg.v != 1 {
            return Err(("bad_request", "BAD_REQUEST", "unsupported quic proxy protocol version"));
        }
        if !valid_stream_id(&msg.stream_id) {
            return Err(("bad_request", "BAD_REQUEST", "invalid stream_id"));
        }
        if msg.access_jwt.len() > JWT_MAX {
            return Err(("bad_request", "BAD_REQUEST", "access_jwt too large"));
        }
        if msg.device_fp.len() > DEVICE_FP_MAX {
            return Err(("bad_request", "BAD_REQUEST", "device_fp too large"));
        }
        match msg.role.as_str() {
            "a" => Ok(()),
            "b" => {
                // The format is strictly validated in verify_join_token; here we only block empty/oversized values to avoid inflating a 4KiB control frame.
                if msg.token.is_empty() || msg.token.len() > JOIN_TOKEN_MAX {
                    return Err(("bad_request", "BAD_REQUEST", "joiner must present the join token"));
                }
                Ok(())
            }
            _ => Err(("bad_request", "BAD_REQUEST", "role must be a|b")),
        }
    }

    /// QUIC registration auth (PL-13 13.3): JWT → device ownership/fingerprint → stream-sig session participant.
    ///
    /// Identity comes **only** from JWT claims after server-side verification (`sub`/`dev`); any client-reported `user`-like field is
    /// never trusted; the join token only locates the stream/pairing. Any failing step is fail-closed.
    pub(crate) async fn authenticate_register(
        state: &AppState,
        msg: &RegisterMsg,
    ) -> Result<AuthedPeer, AuthFailure> {
        // 1) JWT: signature/issuer/expiry (reusing the unified entry; failures also count into key_verification_failures_total)
        let access_jwt = msg.access_jwt.trim();
        if access_jwt.is_empty() {
            return Err(AuthFailure::BadJwt);
        }
        let claims = match state.verify_jwt(access_jwt) {
            Ok(c) => c,
            Err(e) => {
                let reason = e
                    .details
                    .as_ref()
                    .and_then(|d| d.get("reason"))
                    .and_then(|v| v.as_str())
                    .unwrap_or("other");
                return Err(if reason == "expired" {
                    AuthFailure::Expired
                } else {
                    AuthFailure::BadJwt
                });
            }
        };
        if claims.sub.is_empty() || claims.dev.is_empty() {
            return Err(AuthFailure::BadJwt);
        }

        // 2) Device binding: look up the row in devices by the dev claim; it must belong to the sub user, be unrevoked, and match the fingerprint
        let device = match pg::device_by_id(&state.db, &claims.dev).await {
            Ok(Some(d)) => d,
            Ok(None) => return Err(AuthFailure::DeviceMismatch),
            Err(e) => {
                // Fail-closed when a dependency is unavailable (a dead DB must not count as auth success), counted as bad_jwt with a warn.
                tracing::warn!(error = %e, "quic: device lookup failed during register auth");
                return Err(AuthFailure::BadJwt);
            }
        };
        if device.user_id != claims.sub || device.revoked_at.is_some() {
            return Err(AuthFailure::DeviceMismatch);
        }
        let reported_fp = msg.device_fp.trim();
        if reported_fp.is_empty() {
            return Err(AuthFailure::DeviceMismatch);
        }
        match device.fingerprint.as_deref() {
            Some(expected) if !expected.is_empty() && expected == reported_fp => {}
            _ => return Err(AuthFailure::DeviceMismatch),
        }

        // 3) Participant: in the `lattice:stream:{id}` session established by the stream-sig offer, this identity must be on the role's side
        let session = match state.redis.stream_session_get(&msg.stream_id).await {
            Ok(Some(s)) => s,
            Ok(None) => return Err(AuthFailure::NotParticipant),
            Err(e) => {
                tracing::warn!(error = %e, stream_id = %msg.stream_id, "quic: stream session lookup failed during register auth");
                return Err(AuthFailure::NotParticipant);
            }
        };
        let (user_field, device_field, peer_user_field, peer_device_field) = match msg.role.as_str() {
            "a" => ("a_user", "a_device", "b_user", "b_device"),
            "b" => ("b_user", "b_device", "a_user", "a_device"),
            // Already blocked by validate_register; this is a fail-closed fallback
            _ => return Err(AuthFailure::NotParticipant),
        };
        let own_user_ok = session.get(user_field).map(|v| v == &claims.sub).unwrap_or(false);
        let own_device_ok = session.get(device_field).map(|v| v == &device.id).unwrap_or(false);
        let peer_complete = session
            .get(peer_user_field)
            .map(|v| !v.is_empty())
            .unwrap_or(false)
            && session
                .get(peer_device_field)
                .map(|v| !v.is_empty())
                .unwrap_or(false);
        if !(own_user_ok && own_device_ok && peer_complete) {
            return Err(AuthFailure::NotParticipant);
        }

        Ok(AuthedPeer {
            user_id: claims.sub,
            device_id: device.id,
        })
    }


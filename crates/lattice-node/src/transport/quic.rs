        #[test]
        fn join_token_roundtrip_binds_stream_and_expiry() {
            let key = impl_::new_join_token_key();
            let (token, expires) =
                impl_::issue_join_token(&key, "st-quic-1", std::time::Duration::from_secs(60));
            // Format: qj1|<stream_id>|join|<exp>|<nonce>|<mac>
            let parts: Vec<&str> = token.split('|').collect();
            assert_eq!(parts.len(), 6, "token {token}");
            assert_eq!(parts[0], impl_::JOIN_TOKEN_PREFIX);
            assert_eq!(parts[1], "st-quic-1");
            assert_eq!(parts[2], impl_::JOIN_TOKEN_PURPOSE);
            assert_eq!(parts[5].len(), 64, "hmac-sha256 hex");
            assert!(expires > std::time::Instant::now());
            assert!(impl_::verify_join_token(&key, &token, "st-quic-1").is_ok());
            // Bound to stream_id: another stream does not accept it
            assert_eq!(
                impl_::verify_join_token(&key, &token, "st-quic-2"),
                Err(impl_::JoinTokenError::WrongStream)
            );
            // A different key (= node restart/cross-node) does not accept it
            assert_eq!(
                impl_::verify_join_token(&impl_::new_join_token_key(), &token, "st-quic-1"),
                Err(impl_::JoinTokenError::BadMac)
            );
            // Tamper with the stream_id inside the payload (without re-signing) → bad signature
            let mut tampered = token.clone();
            tampered = tampered.replacen("st-quic-1", "st-quic-9", 1);
            assert_eq!(
                impl_::verify_join_token(&key, &tampered, "st-quic-9"),
                Err(impl_::JoinTokenError::BadMac)
            );
            // Wrong purpose / corrupt structure
            let purpose_swapped = token.replacen("|join|", "|data|", 1);
            assert_eq!(
                impl_::verify_join_token(&key, &purpose_swapped, "st-quic-1"),
                Err(impl_::JoinTokenError::WrongPurpose)
            );
            assert!(matches!(
                impl_::verify_join_token(&key, "not-a-token", "st-quic-1"),
                Err(impl_::JoinTokenError::Malformed)
            ));
            assert!(matches!(
                impl_::verify_join_token(&key, &"x".repeat(impl_::JOIN_TOKEN_MAX + 1), "st-quic-1"),
                Err(impl_::JoinTokenError::Malformed)
            ));
        }


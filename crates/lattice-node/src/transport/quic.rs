/// Media-plane path selection (the single order).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MediaPath {
    /// Default: media does not go through the server
    WebRtcDirect,
    /// Switched on per tenant/scenario: corporate networks block UDP, or recording/compliance control is needed
    QuicProxy,
    /// Final fallback: WS tunnel (degraded latency SLA)
    WsTunnel,
}

pub fn choose_path(udp_probe_ok: bool, proxy_enabled: bool) -> MediaPath {
    if !udp_probe_ok {
        return MediaPath::WsTunnel;
    }
    if proxy_enabled {
        MediaPath::QuicProxy
    } else {
        MediaPath::WebRtcDirect
    }
}


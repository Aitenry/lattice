//! Storage lifecycle (REMAINING E01 / PL-02 / ⑥ §2.5, §2.6, §4.1).
//!
//! Two background job groups (both switched by the `[maintenance]` config section, off by default = zero side effects):
//! - [`archive`]: `lock:archive` cold archive — expired messages / whole-month partitions → SQL data export → zstd →
//!   upload `lattice-cold` (or `[maintenance] archive_bucket`) → on success delete rows / `DETACH` partitions;
//!   on failure keep the data and retry next round;
//! - `lock:gc-objects` inside [`archive`]: orphan object GC in the cold bucket (reverse diff over `payload_ref` /
//!   `chunks_index.storage_key`, never deleting objects in use).
//!
//! Boundaries and authority:
//! - Archive format = **replayable SQL text** (`insert into ...` statements + header comment metadata) compressed with zstd,
//!   same convention as design §2.5 ("`pg_dump --data-only` → zstd → `lattice-cold/archive/<table>/...`"),
//!   but generated by the node itself in SQL (no host `pg_dump`; without zstd it degrades to a valid uncompressed zstd
//!   frame, still decompressible with `zstd -d`);
//! - **Upload first, delete later**: delete rows / `DETACH` only after all object uploads succeed; any failure keeps data online;
//! - Partitions are only `DETACH`ed, **never `DROP`ped** (design §2.5 steps 4/5: manual approval after an observation window);
//! - Serialized with `lock:dedup-clean` (same `lock:archive` mutex, ⑥ §6.3 P7).

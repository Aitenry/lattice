/// Result of one cold archive round (for logs/audit/test assertions; failures do not return `Err`, they accumulate in `errors`).
#[derive(Debug, Clone, Default, Serialize)]
pub struct ArchiveSummary {
    pub enabled: bool,
    /// MinIO unavailable → this round short-circuits (② §4.8 object maintenance pause).
    pub paused: bool,
    /// Effective online retention in days.
    pub cutoff_days: i64,
    /// Whole partitions due this round (including failed ones and those cut off by the per-round cap).
    pub partitions_seen: u64,
    /// Partitions successfully exported, uploaded, and `DETACH`ed.
    pub partitions_archived: u64,
    /// Partitions that failed to archive (kept, retried next round).
    pub partitions_failed: u64,
    /// Messages archived at row level and deleted from the online table.
    pub rows_archived: u64,
    /// `message_dedup` rows exported in step (by partition range and by row-batch id).
    pub dedup_rows_exported: u64,
    /// Archive objects uploaded successfully (SQL chunks + manifest; excluding orphan GC).
    pub objects_uploaded: u64,
    /// Failed uploads/queries.
    pub objects_failed: u64,
    /// Total errors this round (upload/DDL/SQL failures; bounded by [`ARCHIVE_ERROR_BUDGET`]).
    pub errors: u64,
    /// Partition names `DETACH`ed this round (audit trail).
    pub detached_partitions: Vec<String>,
}

impl ArchiveSummary {
    /// Whether the round completed cleanly (for log/audit decisions).
    pub fn ok(&self) -> bool {
        self.errors == 0 && self.objects_failed == 0
    }
}


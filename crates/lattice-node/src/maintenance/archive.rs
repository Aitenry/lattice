    /// Minimal decoder for tests: decodes only our own raw-block frame (verifies frame structure/length/block split).
    fn decode_stored_frame(frame: &[u8]) -> Option<Vec<u8>> {
        if frame.len() < 6 || frame[..4] != [0x28, 0xB5, 0x2F, 0xFD] {
            return None;
        }
        let fhd = frame[4];
        if fhd & 0x20 == 0 {
            return None; // expect Single_Segment
        }
        if fhd & 0x04 != 0 {
            return None; // no checksum used
        }
        let flag = (fhd >> 6) & 0x3;
        let (fcs_len, fcs): (usize, u64) = match flag {
            0 => (1, frame[5] as u64),
            1 => {
                if frame.len() < 7 {
                    return None;
                }
                (2, u16::from_le_bytes([frame[5], frame[6]]) as u64 + 256)
            }
            2 => {
                if frame.len() < 9 {
                    return None;
                }
                (4, u32::from_le_bytes([frame[5], frame[6], frame[7], frame[8]]) as u64)
            }
            _ => {
                if frame.len() < 13 {
                    return None;
                }
                let mut b = [0u8; 8];
                b.copy_from_slice(&frame[5..13]);
                (8, u64::from_le_bytes(b))
            }
        };
        let mut off = 5 + fcs_len;
        let mut out = Vec::new();
        loop {
            if off + 3 > frame.len() {
                return None;
            }
            let h = frame[off] as u32 | ((frame[off + 1] as u32) << 8) | ((frame[off + 2] as u32) << 16);
            off += 3;
            let last = h & 1 != 0;
            let btype = (h >> 1) & 3;
            let size = ((h >> 3) & 0x1F_FFFF) as usize;
            if btype != 0 {
                return None; // only Raw blocks supported
            }
            if off + size > frame.len() {
                return None;
            }
            out.extend_from_slice(&frame[off..off + size]);
            off += size;
            if last {
                break;
            }
        }
        if fcs != out.len() as u64 {
            return None;
        }
        Some(out)
    }

    #[test]
    fn stored_zstd_frame_roundtrips_small_medium_large() {
        for size in [1usize, 255, 256, 257, 65_791, 65_792, 200_000, 300_000] {
            let mut data = Vec::with_capacity(size);
            for i in 0..size {
                data.push((i * 31 + 7) as u8);
            }
            let frame = stored_zstd_frame(&data).unwrap();
            assert_eq!(frame[..4], [0x28, 0xB5, 0x2F, 0xFD]);
            let decoded = decode_stored_frame(&frame).expect("frame decodable");
            assert_eq!(decoded, data, "size={size}");
            // Over 128KiB must split into multiple blocks (last flag on the final block)
            let blocks = frame.len() - (5 + 1) - data.len();
            let _ = blocks;
        }
        // Empty input is a caller logic error: must be Err, never an indecompressible frame
        assert!(stored_zstd_frame(&[]).is_err());
    }

    #[test]
    fn stored_zstd_frame_block_split_at_128k() {
        let data = vec![0xABu8; 128 * 1024 + 10];
        let frame = stored_zstd_frame(&data).unwrap();
        // Parse block headers: first block 128KiB (not last), second block 10 bytes (last)
        let mut off = 5 + 4; // 300KB → FCS flag=2 (4 bytes)
        let h1 = frame[off] as u32 | ((frame[off + 1] as u32) << 8) | ((frame[off + 2] as u32) << 16);
        assert_eq!(h1 & 1, 0, "first block is not last");
        assert_eq!((h1 >> 3) & 0x1F_FFFF, 128 * 1024);
        off += 3 + 128 * 1024;
        let h2 = frame[off] as u32 | ((frame[off + 1] as u32) << 8) | ((frame[off + 2] as u32) << 16);
        assert_eq!(h2 & 1, 1, "second block is last");
        assert_eq!((h2 >> 3) & 0x1F_FFFF, 10);
    }


/// Upload one archive object (uncompressed) and record metrics.
async fn put_object(
    st: &Arc<AppState>,
    bucket: &str,
    key: &str,
    bytes: &[u8],
) -> Result<(), String> {
    match st.s3.put_bytes(bucket, key, bytes).await {
        Ok(()) => {
            st.metrics
                .archive_objects_total
                .with_label_values(&["uploaded"])
                .inc();
            Ok(())
        }
        Err(e) => {
            st.metrics
                .archive_objects_total
                .with_label_values(&["failed"])
                .inc();
            Err(e)
        }
    }
}


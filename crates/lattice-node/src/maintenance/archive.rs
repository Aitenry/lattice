        // quote_ident does not quote ordinary lowercase identifiers (the actual PG output form)
        assert!(safe_partition_ident("messages_y2026m07", "messages_y2026m07"));
        assert!(safe_partition_ident("messages_y2026m07", "\"messages_y2026m07\""));

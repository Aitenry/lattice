/// Run one cold archive round (the caller owns the `lock:archive` mutex).
///
/// Returns `Ok(ArchiveSummary)`: a single data failure does not abort the round (counted in `errors`, bounded by the error budget);
/// only pre-queries such as "select expired partitions" return `Err` (retried next round).
pub async fn archive_round_once(st: &Arc<AppState>) -> crate::error::Result<ArchiveSummary> {
    let mut summary = ArchiveSummary::default();
    if !st.cfg.maintenance.archive_should_run() {
        return Ok(summary);
    }
    summary.enabled = true;
    summary.cutoff_days = st.cfg.maintenance.effective_archive_after_days();
    st.metrics.archive_enabled.set(1);

    // MinIO unavailable → pause this round (② §4.8): do not wait for connection failures per object; the next round continues after recovery.
    if let Err(e) = st.s3.probe().await {
        summary.paused = true;
        st.metrics
            .archive_rounds_total
            .with_label_values(&["paused"])
            .inc();
        tracing::warn!(
            error = %e,
            "archive paused: s3 unreachable (will retry next round)"
        );
        return Ok(summary);
    }

    let bucket = st.cfg.maintenance.effective_archive_bucket(&st.cfg.s3);
    if bucket.trim().is_empty() {
        summary.errors += 1;
        st.metrics.archive_rounds_total.with_label_values(&["error"]).inc();
        tracing::warn!("archive skipped: empty archive bucket (check [maintenance] archive_bucket / [s3] bucket_cold)");
        return Ok(summary);
    }
    let cutoff = Utc::now() - ChronoDuration::days(summary.cutoff_days);

    // ---- 1) Whole-partition DETACH fast path (partition upper bound <= cutoff) --------------------------------
    let partitions = match expired_message_partitions(st, cutoff).await {
        Ok(p) => p,
        Err(e) => {
            summary.errors += 1;
            st.metrics.archive_rounds_total.with_label_values(&["error"]).inc();
            tracing::warn!(error = %e, "archive: list expired message partitions failed (retry next round)");
            return Ok(summary);
        }
    };
    summary.partitions_seen = partitions.len() as u64;
    for part in partitions.iter().take(ARCHIVE_PARTITIONS_PER_ROUND) {
        if summary.errors >= ARCHIVE_ERROR_BUDGET {
            tracing::warn!(
                errors = summary.errors,
                "archive: error budget exhausted; remaining partitions deferred to next round"
            );
            break;
        }
        match archive_partition_once(st, part, &bucket, summary.cutoff_days).await {
            Ok(out) => {
                summary.partitions_archived += 1;
                summary.rows_archived += out.rows;
                summary.dedup_rows_exported += out.dedup_rows;
                summary.objects_uploaded += out.objects_uploaded;
                summary.detached_partitions.push(part.name.clone());
                st.metrics
                    .archive_partitions_total
                    .with_label_values(&["detached"])
                    .inc();
                st.metrics
                    .archive_rows_total
                    .with_label_values(&["archived"])
                    .inc_by(out.rows);
                st.metrics
                    .archive_rows_total
                    .with_label_values(&["dedup_exported"])
                    .inc_by(out.dedup_rows);
                tracing::info!(
                    partition = %part.name,
                    rows = out.rows,
                    dedup_rows = out.dedup_rows,
                    objects = out.objects_uploaded,
                    "archive: partition exported and detached (kept for observation, not dropped)"
                );
            }
            Err(e) => {
                summary.partitions_failed += 1;
                summary.errors += 1;
                st.metrics
                    .archive_partitions_total
                    .with_label_values(&["failed"])
                    .inc();
                tracing::warn!(
                    error = %e,
                    partition = %part.name,
                    "archive: partition failed (kept online; retry next round)"
                );
            }
        }
    }

    // ---- 2) Row-level archiving (expired rows inside partially expired partitions) ---------------------------------------
    for _ in 0..ARCHIVE_ROW_BATCHES_PER_ROUND {
        if summary.errors >= ARCHIVE_ERROR_BUDGET {
            break;
        }
        match archive_row_batch_once(st, &bucket, cutoff).await {
            Ok(Some(out)) => {
                summary.rows_archived += out.rows;
                summary.dedup_rows_exported += out.dedup_rows;
                summary.objects_uploaded += out.objects_uploaded;
                st.metrics
                    .archive_rows_total
                    .with_label_values(&["archived"])
                    .inc_by(out.rows);
                st.metrics
                    .archive_rows_total
                    .with_label_values(&["dedup_exported"])
                    .inc_by(out.dedup_rows);
                tracing::info!(
                    rows = out.rows,
                    dedup_rows = out.dedup_rows,
                    batch = %out.batch,
                    "archive: row batch exported and removed from online table"
                );
            }
            Ok(None) => break, // no more expired rows
            Err(e) => {
                summary.errors += 1;
                st.metrics
                    .archive_rows_total
                    .with_label_values(&["failed"])
                    .inc();
                tracing::warn!(error = %e, "archive: row batch failed (rows kept; retry next round)");
            }
        }
    }

    // ---- 3) Result metrics --------------------------------------------------------------
    if summary.ok() {
        st.metrics
            .archive_last_success_unixtime
            .set(Utc::now().timestamp());
        st.metrics.archive_rounds_total.with_label_values(&["ok"]).inc();
    } else {
        st.metrics.archive_rounds_total.with_label_values(&["error"]).inc();
    }
    Ok(summary)
}


/// A `messages` monthly partition whose **whole partition has expired**.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ExpiredPartition {
    /// Partition table name (e.g. `messages_y2026m07`).
    pub name: String,
    /// Safe identifier after `quote_ident()` (for DDL, avoiding injection through concatenation).
    pub quoted: String,
    /// Partition lower bound (inclusive).
    pub from: DateTime<Utc>,
    /// Partition upper bound (exclusive).
    pub to: DateTime<Utc>,
}

/// Parse the `FOR VALUES FROM (...) TO (...)` output of PG `pg_get_expr(relpartbound)`.
///
/// Accepts `2026-07-01 00:00:00+00`, RFC3339, and date-only forms; returns `None` on parse failure
/// (the caller must not guess bounds — a wrong guess would archive unexpired data).
pub fn parse_partition_bound(bound: &str) -> Option<(DateTime<Utc>, DateTime<Utc>)> {
    let from_marker = "FROM ('";
    let to_marker = "') TO ('";
    let start = bound.find(from_marker)? + from_marker.len();
    let rest = &bound[start..];
    let mid = rest.find(to_marker)?;
    let from_s = &rest[..mid];
    let rest = &rest[mid + to_marker.len()..];
    let end = rest.find("')")?;
    let to_s = &rest[..end];
    Some((parse_pg_timestamp(from_s)?, parse_pg_timestamp(to_s)?))
}

fn parse_pg_timestamp(s: &str) -> Option<DateTime<Utc>> {
    let s = s.trim();
    // PG emits e.g. "2026-07-01 00:00:00+00"; `%#z` accepts both +00/+0000 time zone spellings.
    if let Ok(d) = DateTime::parse_from_str(s, "%Y-%m-%d %H:%M:%S%#z") {
        return Some(d.with_timezone(&Utc));
    }
    if let Ok(d) = DateTime::parse_from_str(s, "%Y-%m-%d %H:%M:%S %#z") {
        return Some(d.with_timezone(&Utc));
    }
    if let Ok(d) = DateTime::parse_from_rfc3339(s) {
        return Some(d.with_timezone(&Utc));
    }
    if let Ok(nd) = chrono::NaiveDate::parse_from_str(s, "%Y-%m-%d") {
        return Some(Utc.from_utc_datetime(&nd.and_hms_opt(0, 0, 0)?));
    }
    None
}

/// Whether the object key belongs to a namespace **protected** from orphan GC (archive/backup/WAL/base).
pub fn object_gc_protected(key: &str) -> bool {
    OBJECT_GC_PROTECTED_PREFIXES
        .iter()
        .any(|p| key.starts_with(p))
}

/// Partition object prefix: `archive/messages/<partition>` (manifest in the same directory).
pub fn partition_object_prefix(table: &str, unit: &str) -> String {
    format!("{ARCHIVE_OBJECT_PREFIX}{table}/{unit}")
}

/// Row batch object key: `archive/<table>/rows/<batch>.sql.zst` (deterministic naming → retries overwrite the same object).
pub fn row_batch_object_key(table: &str, batch: &str) -> String {
    format!("{ARCHIVE_OBJECT_PREFIX}{table}/rows/{batch}.sql.zst")
}


/// Archive one batch of expired rows (upload first, delete after; deterministic object keys → idempotent retries).
///
/// Returns `Ok(None)` = no more expired rows (not an error); `Err` = this round failed, online rows kept.
async fn archive_row_batch_once(
    st: &Arc<AppState>,
    bucket: &str,
    cutoff: DateTime<Utc>,
) -> crate::error::Result<Option<RowBatchOutcome>> {
    // 1) Select the batch: bounded by accumulating payload bytes (always take at least 1 item, even a huge one, so selection never stalls).
    let ids: Vec<(String, DateTime<Utc>)> = sqlx::query_as(
        "with expired as (
            select id, created_at, coalesce(size, 0) as sz
              from messages
             where created_at < $1::timestamptz
             order by created_at, id
             limit $2
         ), bounded as (
            select id, created_at, sz,
                   sum(sz) over (order by created_at, id) as cum
              from expired
         )
         select id, created_at from bounded
          where cum <= $3 or cum = sz
          order by created_at, id",
    )
    .bind(cutoff)
    .bind(ARCHIVE_ROW_BATCH_MAX)
    .bind(ARCHIVE_ROW_PAYLOAD_BYTES_MAX)
    .fetch_all(&st.db)
    .await
    .map_err(crate::error::db)?;
    if ids.is_empty() {
        return Ok(None);
    }
    let id_list: Vec<String> = ids.iter().map(|(id, _)| id.clone()).collect();
    let batch = format!("{}-{}", cutoff.format("%Y%m%d"), id_list[0]);
    let mut out = RowBatchOutcome {
        batch: batch.clone(),
        rows: 0,
        dedup_rows: 0,
        objects_uploaded: 0,
    };

    // 2) Generate data-only SQL for messages (server-side, keeping bytea out of node memory).
    let stmt_expr = "select 'insert into messages (id,conv_id,sender,env_type,content_type,size,\
                      chunk_total,payload,payload_ref,status,seq,created_at,expires_at) values (' || \
                      quote_nullable(id) || ',' || quote_nullable(conv_id) || ',' || \
                      quote_nullable(sender) || ',' || quote_nullable(env_type) || ',' || \
                      quote_nullable(content_type) || ',' || size::text || ',' || \
                      chunk_total::text || ',' || \
                      case when payload is null then 'null' \
                           else 'decode(' || quote_literal(encode(payload, 'hex')) || ',' || \
                                quote_literal('hex') || ')' end || ',' || \
                      quote_nullable(payload_ref) || ',' || quote_nullable(status) || ',' || \
                      seq::text || ',' || quote_literal(created_at::text) || '::timestamptz,' || \
                      case when expires_at is null then 'null' \
                           else quote_literal(expires_at::text) || '::timestamptz' end || ');'";
    let q = format!(
        "select payload_ref, ({stmt_expr}) as stmt from messages \
          where id = any($1) and created_at < $2 order by created_at, id"
    );
    let mut body = String::new();
    let mut payload_keys: BTreeSet<String> = BTreeSet::new();
    {
        use futures::TryStreamExt;
        let mut stream = sqlx::query_as::<_, (Option<String>, String)>(&q)
            .bind(&id_list)
            .bind(cutoff)
            .fetch(&st.db);
        while let Some((payload_ref, stmt)) = stream.try_next().await.map_err(crate::error::db)? {
            if let Some(k) = payload_ref.as_deref().map(str::trim).filter(|k| !k.is_empty()) {
                payload_keys.insert(k.to_string());
            }
            body.push_str(&stmt);
            body.push('\n');
            out.rows += 1;
        }
    }
    if out.rows == 0 {
        // Extreme concurrency: rows were deleted by purge/another node; process nothing this round and reselect next round.
        return Ok(Some(out));
    }

    // 3) Upload the messages SQL object (single object bounded ≤ ~8MiB payload → text ≤ ~16MiB).
    let key = row_batch_object_key("messages", &batch);
    let mut raw = String::with_capacity(body.len() + 256);
    raw.push_str(&archive_sql_header("messages", &batch, 0));
    raw.push_str(&body);
    put_compressed(st, bucket, &key, raw.as_bytes())
        .await
        .map_err(|e| crate::error::internal(format!("archive row batch upload {key}: {e}")))?;
    out.objects_uploaded += 1;

    // 4) Export message_dedup for this batch in step (two key classes: msg_id and `<msg_id>.c<i>`).
    let patterns: Vec<String> = id_list.iter().map(|id| format!("{id}.c%")).collect();
    let dedup_q = "select 'insert into message_dedup (id,conv_id,created_at,expires_at) values (' || \
                           quote_nullable(id) || ',' || quote_nullable(conv_id) || ',' || \
                           quote_literal(created_at::text) || '::timestamptz,' || \
                           case when expires_at is null then 'null' \
                                else quote_literal(expires_at::text) || '::timestamptz' end || ');' \
                     from message_dedup where id = any($1) or id like any($2) \
                    order by created_at, id";
    let mut dedup_body = String::new();
    {
        use futures::TryStreamExt;
        let mut stream = sqlx::query_as::<_, (String,)>(dedup_q)
            .bind(&id_list)
            .bind(&patterns)
            .fetch(&st.db);
        while let Some((stmt,)) = stream.try_next().await.map_err(crate::error::db)? {
            dedup_body.push_str(&stmt);
            dedup_body.push('\n');
            out.dedup_rows += 1;
        }
    }
    if !dedup_body.is_empty() {
        let dedup_key = row_batch_object_key("message_dedup", &batch);
        let mut raw = String::with_capacity(dedup_body.len() + 256);
        raw.push_str(&archive_sql_header("message_dedup", &batch, 0));
        raw.push_str(&dedup_body);
        put_compressed(st, bucket, &dedup_key, raw.as_bytes())
            .await
            .map_err(|e| {
                crate::error::internal(format!("archive dedup batch upload {dedup_key}: {e}"))
            })?;
        out.objects_uploaded += 1;
    }
    upload_manifest(
        st,
        bucket,
        &row_batch_manifest_key("messages", &batch),
        json!({
            "format": ARCHIVE_FORMAT_V1,
            "kind": "rows",
            "table": "messages",
            "batch": batch,
            "cutoff": cutoff.to_rfc3339(),
            "from": ids.first().map(|(_, t)| t.to_rfc3339()),
            "to": ids.last().map(|(_, t)| t.to_rfc3339()),
            "rows": out.rows,
            "dedup_rows": out.dedup_rows,
            "compression": "zstd",
            "note": "data-only insert statements; rows deleted from online table after upload",
            "created_at": Utc::now().to_rfc3339(),
        }),
    )
    .await?;
    out.objects_uploaded += 1;

    // 5) Payload object reclamation candidates (grace period + reverse diff, double protection).
    record_orphan_candidates(st, &st.cfg.s3.bucket_large, &payload_keys, "messages.payload_ref").await;
    // Chunk objects (if any) are registered too: deletion is rechecked by reverse diff against chunks_index.storage_key.
    let chunk_keys: Vec<String> = sqlx::query_scalar(
        "select storage_key from chunks_index where msg_id = any($1) and storage_key is not null",
    )
    .bind(&id_list)
    .fetch_all(&st.db)
    .await
    .map_err(crate::error::db)?;
    let chunk_keys: BTreeSet<String> = chunk_keys
        .into_iter()
        .map(|k| k.trim().to_string())
        .filter(|k| !k.is_empty())
        .collect();
    record_orphan_candidates(st, &st.cfg.s3.bucket_large, &chunk_keys, "chunks_index.storage_key").await;

    // 6) Delete online only after all uploads succeed (same transaction: dedup + messages; rollback on failure).
    let mut tx = st.db.begin().await.map_err(crate::error::db)?;
    sqlx::query("delete from message_dedup where id = any($1) or id like any($2)")
        .bind(&id_list)
        .bind(&patterns)
        .execute(&mut *tx)
        .await
        .map_err(crate::error::db)?;
    let deleted = sqlx::query("delete from messages where id = any($1) and created_at < $2")
        .bind(&id_list)
        .bind(cutoff)
        .execute(&mut *tx)
        .await
        .map_err(crate::error::db)?
        .rows_affected();
    tx.commit().await.map_err(crate::error::db)?;
    out.rows = deleted;
    tracing::debug!(
        batch = %batch,
        selected = id_list.len(),
        deleted,
        dedup_rows = out.dedup_rows,
        "archive: row batch removed from online table"
    );
    Ok(Some(out))
}


//! Cold partition/row archiving + cold-bucket orphan object GC (REMAINING E01 / PL-02 / ⑥ §2.5, §2.6, §4.1).
//!
//! # Archive semantics (`lock:archive`, daily; serialized with `lock:dedup-clean`)
//!
//! 1. **Select expired data**: `created_at < now() - [maintenance] archive_after_days` (default 30 days);
//!    a monthly partition takes the `DETACH` fast path only when **the whole partition is expired** (partition upper bound <= cutoff);
//!    expired rows inside "partially expired" partitions go through row-level archiving (otherwise the 30-day online retention could never be met —
//!    monthly partitions span more than 30 days, exactly the criticism design §2.5 makes of `metric_snapshot`).
//! 2. **Export**: render rows as SQL text of the form `insert into messages (...) values (...)` / `insert into
//!    message_dedup (...)` (the same replayable format as design §2.5 "`pg_dump --data-only` → zstd →
//!    `lattice-cold/archive/<table>/<partition>.sql.zst`"; generated by the node itself in SQL,
//!    without the host `pg_dump` binary), compress with zstd, and upload to the cold bucket:
//!    - partitions: `archive/messages/<partition>/part-00000.sql.zst` + `manifest.json`;
//!    - row batches: `archive/messages/rows/<batch>.sql.zst`;
//!    - dedup records (⑥ §6.3 P7: same lifetime as messages, must be exported in step): `archive/message_dedup/...`.
//! 3. **Delete only after success**: delete online rows / `DETACH` partitions only after all object uploads succeed; any failure keeps the online
//!    data and retries next round (deterministic object keys → retries overwrite the same object, no duplicate archives).
//! 4. **DETACH only, never DROP** (design §2.5 steps 4/5: keep the observation window, then DROP after manual approval).
//!
//! # Orphan object GC semantics (`lock:gc-objects`, daily; off by default)
//!
//! Only two classes of **archived/cold-bucket** candidates are handled, and before deleting, each is rechecked by reverse diff against `payload_ref` / `chunks_index.storage_key`;
//! **anything still referenced by online rows is skipped** (⑥ §4.1 "lifecycle rules cannot replace reference comparison"):
//! - payload object candidates registered at archive time (`lattice:archive:orphan-candidates`, Redis JSON,
//!   reclaimed after the `object_gc_grace_days` grace period; losing Redis only leaves objects longer, never deletes wrongly);
//! - cold-bucket objects **outside the `archive/`, `backup/`, `wal/`, `pg/`, `base/` namespaces**, past the grace period,
//!   and not referenced by any PG row.
//!
//! **Explicitly out of scope**: whole-bucket scan-and-delete of `lattice-large` (the hot bucket) — hot-bucket objects are live payloads of file messages;
//! a whole-bucket scan plus reverse diff would need a full `ListObjectsV2` comparison, and wrongful deletion is too costly; this round follows the task card and covers only
//! cold-bucket/archived objects (design §4.1's "delete 30 days after `payload_ref` invalidation" is implemented by candidate registration + reverse diff,
//! and hot-bucket objects are deleted only when registered as candidates at archive time).

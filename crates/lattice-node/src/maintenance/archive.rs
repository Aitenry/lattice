/// Archive one whole partition: export messages + same-range message_dedup → upload → register payload candidates →
/// delete the dedup range in a transaction + `DETACH` the partition (no DROP).
async fn archive_partition_once(
    st: &Arc<AppState>,
    part: &ExpiredPartition,
    bucket: &str,
    cutoff_days: i64,
) -> crate::error::Result<PartitionOutcome> {
    if !safe_partition_ident(&part.name, &part.quoted) {
        return Err(crate::error::internal(format!(
            "archive: refuse unsupported partition identifier {:?} / {:?}",
            part.name, part.quoted
        )));
    }
    let mut out = PartitionOutcome::default();

    // messages: stream-generated SQL (server-side quote_nullable/encode, keeping bytea out of node memory).
    let q = format!(
        "select payload_ref,
                'insert into messages (id,conv_id,sender,env_type,content_type,size,chunk_total,\
                 payload,payload_ref,status,seq,created_at,expires_at) values (' || \
                 quote_nullable(id) || ',' || quote_nullable(conv_id) || ',' || \
                 quote_nullable(sender) || ',' || quote_nullable(env_type) || ',' || \
                 quote_nullable(content_type) || ',' || size::text || ',' || \
                 chunk_total::text || ',' || \
                 case when payload is null then 'null' \
                      else 'decode(' || quote_literal(encode(payload, 'hex')) || ',' || \
                           quote_literal('hex') || ')' end || ',' || \
                 quote_nullable(payload_ref) || ',' || quote_nullable(status) || ',' || \
                 seq::text || ',' || quote_literal(created_at::text) || '::timestamptz,' || \
                 case when expires_at is null then 'null' \
                      else quote_literal(expires_at::text) || '::timestamptz' end || ');' as stmt \
           from {} order by created_at, id",
        part.quoted
    );
    let messages_prefix = partition_object_prefix("messages", &part.name);
    let mut payload_keys: BTreeSet<String> = BTreeSet::new();
    let mut parts: Vec<String> = Vec::new();
    let mut body = String::new();
    let mut rows = 0u64;

    {
        use futures::TryStreamExt;
        let mut stream = sqlx::query_as::<_, (Option<String>, String)>(&q).fetch(&st.db);
        while let Some(row) = stream.try_next().await.map_err(crate::error::db)? {
            let (payload_ref, stmt) = row;
            if let Some(k) = payload_ref.as_deref().map(str::trim).filter(|k| !k.is_empty()) {
                payload_keys.insert(k.to_string());
            }
            body.push_str(&stmt);
            body.push('\n');
            rows += 1;
            if body.len() >= ARCHIVE_PART_CHUNK_BYTES {
                flush_part(st, bucket, "messages", &part.name, &messages_prefix, &mut parts, &mut body)
                    .await?;
            }
        }
    }
    if !body.is_empty() || parts.is_empty() {
        flush_part(st, bucket, "messages", &part.name, &messages_prefix, &mut parts, &mut body)
            .await?;
    }
    out.rows = rows;
    out.objects_uploaded += parts.len() as u64;

    // Same-range message_dedup (⑥ §6.3 P7: archiving must export dedup records for the same period).
    let prefix = partition_object_prefix("message_dedup", &part.name);
    let (dedup_rows, dedup_objects) = export_dedup_range(
        st,
        bucket,
        &prefix,
        &part.name,
        part.from,
        part.to,
    )
    .await?;
    out.dedup_rows = dedup_rows;
    out.objects_uploaded += dedup_objects;

    // Upload the manifest last: only when it appears is the unit's complete data set in the cold bucket.
    upload_manifest(
        st,
        bucket,
        &partition_manifest_key("messages", &part.name),
        json!({
            "format": ARCHIVE_FORMAT_V1,
            "kind": "partition",
            "table": "messages",
            "unit": part.name,
            "from": part.from.to_rfc3339(),
            "to": part.to.to_rfc3339(),
            "cutoff_days": cutoff_days,
            "rows": rows,
            "parts": parts,
            "payload_keys": payload_keys.len(),
            "compression": "zstd",
            "note": "data-only insert statements; partition is kept detached for observation (not dropped)",
            "created_at": Utc::now().to_rfc3339(),
        }),
    )
    .await?;
    out.objects_uploaded += 1;
    upload_manifest(
        st,
        bucket,
        &partition_manifest_key("message_dedup", &part.name),
        json!({
            "format": ARCHIVE_FORMAT_V1,
            "kind": "partition",
            "table": "message_dedup",
            "unit": part.name,
            "from": part.from.to_rfc3339(),
            "to": part.to.to_rfc3339(),
            "rows": dedup_rows,
            "parts": dedup_objects,
            "compression": "zstd",
            "created_at": Utc::now().to_rfc3339(),
        }),
    )
    .await?;
    out.objects_uploaded += 1;

    // Reclamation candidates for archived payload objects (deletion allowed only after the grace period; reverse diff as a fallback).
    record_orphan_candidates(st, &st.cfg.s3.bucket_large, &payload_keys, "messages.payload_ref").await;

    // Only touch online data after all uploads succeed: delete the dedup range in the same transaction + DETACH the partition (DDL transactionality;
    // any failure rolls back everything, the partition stays online, and the next round reruns (deterministic object keys → overwrite).
    let mut tx = st.db.begin().await.map_err(crate::error::db)?;
    sqlx::query("delete from message_dedup where created_at >= $1 and created_at < $2")
        .bind(part.from)
        .bind(part.to)
        .execute(&mut *tx)
        .await
        .map_err(crate::error::db)?;
    sqlx::query(&format!(
        "alter table messages detach partition {}",
        part.quoted
    ))
    .execute(&mut *tx)
    .await
    .map_err(crate::error::db)?;
    tx.commit().await.map_err(crate::error::db)?;
    Ok(out)
}

/// Compress the accumulated SQL body into one archive chunk object (zstd) and clear the buffer.
async fn flush_part(
    st: &Arc<AppState>,
    bucket: &str,
    table: &str,
    unit: &str,
    prefix: &str,
    parts: &mut Vec<String>,
    body: &mut String,
) -> crate::error::Result<()> {
    let index = parts.len();
    let key = format!("{prefix}/part-{index:05}.sql.zst");
    let mut raw = String::with_capacity(body.len() + 256);
    raw.push_str(&archive_sql_header(table, unit, index));
    raw.push_str(body);
    put_compressed(st, bucket, &key, raw.as_bytes())
        .await
        .map_err(|e| crate::error::internal(format!("archive upload {key}: {e}")))?;
    parts.push(key);
    body.clear();
    Ok(())
}

/// Export a `message_dedup` time range (partition archive scope) → `(rows, chunks)`.
async fn export_dedup_range(
    st: &Arc<AppState>,
    bucket: &str,
    prefix: &str,
    unit: &str,
    from: DateTime<Utc>,
    to: DateTime<Utc>,
) -> crate::error::Result<(u64, u64)> {
    let q = "select 'insert into message_dedup (id,conv_id,created_at,expires_at) values (' || \
                    quote_nullable(id) || ',' || quote_nullable(conv_id) || ',' || \
                    quote_literal(created_at::text) || '::timestamptz,' || \
                    case when expires_at is null then 'null' \
                         else quote_literal(expires_at::text) || '::timestamptz' end || ');' \
               from message_dedup where created_at >= $1 and created_at < $2 \
              order by created_at, id";
    let mut parts: Vec<String> = Vec::new();
    let mut body = String::new();
    let mut rows = 0u64;
    {
        use futures::TryStreamExt;
        let mut stream = sqlx::query_as::<_, (String,)>(q)
            .bind(from)
            .bind(to)
            .fetch(&st.db);
        while let Some((stmt,)) = stream.try_next().await.map_err(crate::error::db)? {
            body.push_str(&stmt);
            body.push('\n');
            rows += 1;
            if body.len() >= ARCHIVE_PART_CHUNK_BYTES {
                flush_part(st, bucket, "message_dedup", unit, prefix, &mut parts, &mut body).await?;
            }
        }
    }
    if !body.is_empty() || parts.is_empty() {
        flush_part(st, bucket, "message_dedup", unit, prefix, &mut parts, &mut body).await?;
    }
    Ok((rows, parts.len() as u64))
}


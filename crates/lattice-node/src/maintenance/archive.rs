/// Select `messages` monthly partitions whose **whole partition predates the cutoff** (ascending upper bound, oldest first).
pub async fn expired_message_partitions(
    st: &Arc<AppState>,
    cutoff: DateTime<Utc>,
) -> crate::error::Result<Vec<ExpiredPartition>> {
    #[derive(sqlx::FromRow)]
    struct Row {
        name: String,
        quoted: String,
        bound: String,
    }
    let rows: Vec<Row> = sqlx::query_as(
        "select c.relname as name,
                quote_ident(c.relname) as quoted,
                pg_get_expr(c.relpartbound, c.oid) as bound
           from pg_inherits i
           join pg_class c on c.oid = i.inhrelid
           join pg_class p on p.oid = i.inhparent
          where p.relname = 'messages'
            and p.relnamespace = 'public'::regnamespace
          order by pg_get_expr(c.relpartbound, c.oid)",
    )
    .fetch_all(&st.db)
    .await
    .map_err(crate::error::db)?;

    let mut out: Vec<ExpiredPartition> = Vec::new();
    for r in rows {
        let Some((from, to)) = parse_partition_bound(&r.bound) else {
            tracing::warn!(
                partition = %r.name,
                bound = %r.bound,
                "archive: unparsable partition bound; skip (never guess retention boundary)"
            );
            continue;
        };
        if to <= cutoff {
            out.push(ExpiredPartition {
                name: r.name,
                quoted: r.quoted,
                from,
                to,
            });
        }
    }
    out.sort_by_key(|p| p.to);
    Ok(out)
}

